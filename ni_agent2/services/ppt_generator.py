from dataclasses import dataclass
from typing import List

from pptx import Presentation


@dataclass
class SlideSpec:
    title: str
    bullets: List[str]


def parse_outline(outline_text: str) -> List[SlideSpec]:
    slides: List[SlideSpec] = []
    for raw_line in outline_text.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if "|" in line:
            title_part, bullets_part = line.split("|", 1)
            title = title_part.strip()
            bullets = [bullet.strip() for bullet in bullets_part.split(";") if bullet.strip()]
        else:
            title = line
            bullets = []
        slides.append(SlideSpec(title=title, bullets=bullets))
    return slides


def generate_presentation(title: str, outline_text: str, output_path: str) -> int:
    presentation = Presentation()

    title_slide_layout = presentation.slide_layouts[0]
    title_slide = presentation.slides.add_slide(title_slide_layout)
    title_placeholder = title_slide.shapes.title
    title_placeholder.text = title.strip() if title.strip() else "Ni Agent2 Deck"

    subtitle_placeholder = title_slide.placeholders[1]
    subtitle_placeholder.text = "Generated by Ni Agent2"

    bullet_layout = presentation.slide_layouts[1]
    slides = parse_outline(outline_text)
    for slide_spec in slides:
        slide = presentation.slides.add_slide(bullet_layout)
        slide.shapes.title.text = slide_spec.title
        body_shape = slide.shapes.placeholders[1]
        text_frame = body_shape.text_frame
        text_frame.clear()
        if slide_spec.bullets:
            for index, bullet in enumerate(slide_spec.bullets):
                if index == 0:
                    text_frame.text = bullet
                else:
                    paragraph = text_frame.add_paragraph()
                    paragraph.text = bullet
        else:
            text_frame.text = "(No bullets provided)"

    presentation.save(output_path)
    return len(slides) + 1
